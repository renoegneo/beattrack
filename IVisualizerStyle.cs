// interface — не класс, а именно КОНТРАКТ. У него нет тела методов,
// только подписи ("сигнатуры") — что должно быть, без "как именно".
// Реализация ("как именно") будет в каждом конкретном классе отдельно.
public interface IVisualizerStyle
{
    // Вызывается КАЖДЫЙ кадр, перед отрисовкой — сюда прилетают
    // свежие звуковые данные и время с прошлого кадра
    void Update(AudioFrame audio, float deltaTime);

    // Вызывается КАЖДЫЙ кадр, после Update — тут только рисование,
    // никакой логики с числами
    void Draw();
}